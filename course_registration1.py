def main():
    system = CourseSystem()

    while True:
        print("\n1.Load Students  2.Load Courses  3.Load Registrations")
        print("4.Add Student    5.Add Course")
        print("6.Register       7.Drop Course")
        print("8.Show Students  9.Show Courses  10.Show Registrations")
        print("11.Save Data     0.Exit")

        choice = input("Choice: ")

        if choice == "1":
            system.load_students()
        elif choice == "2":
            system.load_courses()
        elif choice == "3":
            system.load_registrations()
        elif choice == "4":
            system.add_student()
        elif choice == "5":
            system.add_course()
        elif choice == "6":
            system.register_course()
        elif choice == "7":
            system.drop_course()
        elif choice == "8":
            system.display_students()
        elif choice == "9":
            system.display_courses()
        elif choice == "10":
            system.display_registrations()
        elif choice == "11":
            system.save_data()
        elif choice == "0":
            print("Exiting...")
            break
        else:
            print("Invalid choice!")

main()

