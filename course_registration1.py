import csv
from abc import ABC, abstractmethod

class Person(ABC):
    def __init__(self, student_id, name):
        self._student_id = student_id
        self._name = name

    @abstractmethod
    def display(self):
        pass

class Student(Person):
    def __init__(self, student_id, name):
        super().__init__(student_id, name)

    def display(self):
        print(self._student_id, self._name)

class Course:
    def __init__(self, course_id, course_name, credits):
        self._course_id = course_id
        self._course_name = course_name
        self._credits = credits

    def display(self):
        print(self._course_id, self._course_name, self._credits)

class CourseSystem:
    def __init__(self):
        self.students = []
        self.courses = []
        self.registrations = []


    students_file = '/students_large.csv'
    courses_file = '/courses_updated.csv'
    registrations_file = '/registrations_realistic.csv'
    def load_students(self):
        try:
            with open(self.students_file, "r") as file:
                reader = csv.DictReader(file)
                for row in reader:
                    self.students.append(Student(row["student_id"], row["name"]))
            print("Students loaded!")
        except Exception as e:
            print("Error loading students:", e)

    def load_courses(self):
        try:
            with open(self.courses_file, "r") as file:
                reader = csv.DictReader(file)
                for row in reader:
                    self.courses.append(
                        Course(row["course_id"], row["course_name"], row["credits"])
                    )
            print("Courses loaded!")
        except Exception as e:
            print("Error loading courses:", e)

    def load_registrations(self):
        try:
            with open(self.registrations_file, "r") as file:
                reader = csv.DictReader(file)
                for row in reader:
                    self.registrations.append([row["student_id"], row["course_id"]])
            print("Registrations loaded!")
        except Exception as e:
            print("Error loading registrations:", e)

    def add_student(self):
        sid = input("Enter ID: ")
        name = input("Enter Name: ")
        self.students.append(Student(sid, name))
        print("Student added!")

    def add_course(self):
        cid = input("Enter Course ID: ")
        name = input("Enter Course Name: ")
        credits = input("Enter Credits: ")
        self.courses.append(Course(cid, name, credits))
        print("Course added!")

    def register_course(self):
        sid = input("Student ID: ")
        cid = input("Course ID: ")
        self.registrations.append([sid, cid])
        print("Registered!")

    def drop_course(self):
        sid = input("Student ID: ")
        cid = input("Course ID: ")

        if [sid, cid] in self.registrations:
            self.registrations.remove([sid, cid])
            print("Dropped!")
        else:
            print("Not found!")

    def display_students(self):
        for s in self.students:
            s.display()

    def display_courses(self):
        for c in self.courses:
            c.display()

    def display_registrations(self):
        for r in self.registrations:
            print("Student:", r[0], "-> Course:", r[1])

    def save_data(self):
        try:
            with open("saved_registrations.csv", "w", newline="") as file:
                writer = csv.writer(file)
                writer.writerow(["student_id", "course_id"])
                writer.writerows(self.registrations)
            print("Saved!")
        except Exception as e:
            print("Error saving:", e)

